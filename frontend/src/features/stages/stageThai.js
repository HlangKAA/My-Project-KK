export function localStageData(stage, key, isThai) {
    if (!isThai || !stage) return stage;
    const hints = chapterTwoHints[key];
    const easier = easierStageThai[key];
    const changedTarget = stage.arena?.colorTargets?.find(target => JSON.stringify(target.sourceRgb) !== JSON.stringify(target.targetRgb));
    const workedExample = easier && stage.visionChecks && changedTarget
        ? ` ตัวอย่าง: ${JSON.stringify(changedTarget.sourceRgb)} เปลี่ยนเป็น ${JSON.stringify(changedTarget.targetRgb)}`
        : '';
    const hintFallbacks = [
        'อ่านโจทย์อีกครั้งแล้วลองแยกเป็นคำสั่งเล็กๆ ทีละขั้น',
        'ดูค่าที่โจทย์ให้กับตัวอย่างในหนังสือคาถา แล้วลองแก้โค้ดทีละจุด',
    ];
    return {
        ...stage,
        objective: easier?.objective || (stage.visionChecks ? (arenaThai[key] || stage.objective) : (objectives[key] || stage.objective)),
        completeMessage: key === '4-7' ? 'แคร็กก์พ่ายแพ้แล้ว สีสันกลับคืนสู่อาณาจักร!' : `${stage.title} สำเร็จแล้ว!`,
        ...(stage.hints ? { hints: stage.hints.map((hint, index) => ({
            ...hint,
            text: easier
                ? (index === 0 ? easier.hint + workedExample : index === 1 ? 'แก้เฉพาะบรรทัดที่มีคำใบ้ โค้ดส่วนอื่นและเส้นทางเตรียมไว้แล้ว' : hint.text)
                : stage.visionChecks ? (hints?.[index] || (index === 0 ? arenaThai[key] : hint.text)) : (hints?.[index] || (index < 2 ? hintFallbacks[index] : hint.text)),
        })) } : {}),
        ...(stage.storyIntro ? {
            storyIntro: {
                ...stage.storyIntro,
                dialogues: stage.storyIntro.dialogues.map((dialogue, index) => ({
                    ...dialogue,
                    text: dialogue.textThai || (index === 0 ? `ยินดีต้อนรับสู่ ${stage.title} มาลองใช้โค้ดแก้ปัญหาไปด้วยกัน` : (easier?.objective || arenaThai[key] || objectives[key] || dialogue.text)),
                })),
                enterButtonText: 'เริ่มด่าน',
            },
        } : {}),
    };
}

export function localRegion(region, isThai) {
    return isThai ? { ...region, ...regionThai[region.id], name: region.name } : region;
}

export function localStage(stage, regionId, isThai) {
    if (!isThai) return stage;
    const [, description] = stageThai[`${regionId}-${stage.id}`] || [];
    return { ...stage, description: easierStageThai[`${regionId}-${stage.id}`]?.description || description || stage.description };
}
